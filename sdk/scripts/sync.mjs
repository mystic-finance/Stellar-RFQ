#!/usr/bin/env node
// Writes src/deployments.ts from ../deployments/<network>.json (addresses only, never accounts).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const pick = (net) => {
  const f = new URL(`../../deployments/${net}.json`, import.meta.url);
  if (!existsSync(f)) return { contracts: {}, wasmHashes: {}, external: {} };
  const d = JSON.parse(readFileSync(f, "utf8"));
  const c = d.contracts ?? {};
  const keep = ["rfq", "router", "facilityAggregator", "dexAggregator", "pushOracle", "soroswapAdapter", "aquariusAdapter"];
  return {
    contracts: Object.fromEntries(keep.filter((k) => c[k]).map((k) => [k, c[k]])),
    wasmHashes: d.wasmHashes ?? {},
    external: d.external ?? {},
  };
};
const out = { testnet: pick("testnet"), mainnet: pick("mainnet") };
writeFileSync(new URL("../src/deployments.ts", import.meta.url),
  `// Generated by scripts/sync.mjs from deployments/*.json. Do not edit.\nexport const deployments = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log(JSON.stringify(out, null, 2));
